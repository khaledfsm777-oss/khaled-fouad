export function getSurahMetadata(surahId: number): SurahMetadata {
  if (SURAH_METADATA[surahId]) {
    return SURAH_METADATA[surahId];
  }
  const foundSurah = ALL_SURAHS.find(s => s.id === surahId);
  const surahName = foundSurah ? foundSurah.name : `السورة ${surahId}`;
  
  const surahVerses = (quranData as any[]).filter(v => v.surahId === surahId);
  const totalVerses = surahVerses.length || 50;

  return {
    id: surahId,
    name: surahName,
    orderInQuran: surahId,
    juzStartEnd: `السورة رقم ${surahId} في المصحف الشريف`,
    hizbStartEnd: `نطاق السورة ${surahId}`,
    nooraniOrder: 'ليست من السور النورانية الـ 29',
    revelationOrder: surahId,
    revelationPlace: surahId <= 86 ? 'مكية' : 'مدنية',
    totalVerses: totalVerses,
    totalWords: totalVerses * 12,
    totalLetters: totalVerses * 50,
    revelationReason: `سورة ${surahName} المباركة، السورة رقم ${surahId} في ترتيب المصحف الشريف.`,
    briefTopic: `تتطرق سورة ${surahName} لموضوعات الإيمان والتوحيد والعبر والمواعظ والاتزان الرقمي في كتاب الله الكريم.`
  };
}
